// Creates the tutor_applications table used by the tutor registration flow.
// Run: node scripts/migrate-tutor-applications.js  (from backend/)
const { pool } = require('../src/config/db');

const sql = `
CREATE TABLE IF NOT EXISTS tutor_applications (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name      VARCHAR(200) NOT NULL,
  email          VARCHAR(190) NOT NULL,
  phone          VARCHAR(30) NOT NULL,
  address        VARCHAR(255) NULL,
  hourly_rate    NUMERIC(10,2) NULL,
  subjects       JSONB NULL,
  license_number VARCHAR(100) NULL,
  institution    VARCHAR(200) NULL,
  specialization VARCHAR(200) NULL,
  years_teaching SMALLINT NULL,
  license_file   VARCHAR(255) NULL,
  id_file        VARCHAR(255) NULL,
  status         TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  reviewed_at    TIMESTAMPTZ NULL,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_tutor_applications_status ON tutor_applications (status);
CREATE INDEX IF NOT EXISTS idx_tutor_applications_created ON tutor_applications (created_at);
`;

(async () => {
  const client = await pool.connect();
  try {
    await client.query(sql);
    console.log('OK: tutor_applications table is ready.');
  } catch (err) {
    console.error('Migration failed:', err.message);
    process.exitCode = 1;
  } finally {
    client.release();
    await pool.end();
  }
})();